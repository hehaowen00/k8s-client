//! Persistent app settings (~/.config/kube-portal/settings.db), kubeconfigs
//! pasted into Kube Portal, and a file watcher that notifies the UI when any
//! kubeconfig source changes.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::sync::Mutex;
use std::time::Duration;

use kube::config::Kubeconfig;
use notify::{RecommendedWatcher, RecursiveMode, Watcher};
use serde::{Deserialize, Serialize};
use tauri::{AppHandle, Emitter, Manager, State};

use crate::state::{err, AppState, Result};

#[derive(Serialize, Deserialize, Default, Clone, Debug, PartialEq)]
#[serde(rename_all = "camelCase", default)]
pub struct ClusterSettings {
    pub display_name: Option<String>,
    /// CSS colour for the cluster's dot / avatar.
    pub color: Option<String>,
    /// Image data URL (downscaled) shown instead of the colour.
    pub icon: Option<String>,
    pub default_namespace: Option<String>,
    /// For users who can't list namespaces: shown instead of listing, and "all namespaces" spans these.
    pub accessible_namespaces: Vec<String>,
    /// http(s):// or socks5:// proxy for API server traffic.
    pub proxy_url: Option<String>,
    /// Shown in the hotbar.
    pub pinned: bool,
    /// What the MCP server may read from this cluster (nothing by default).
    pub mcp: McpAccess,
}

#[derive(Serialize, Deserialize, Default, Clone, Debug, PartialEq)]
#[serde(rename_all = "camelCase", default)]
pub struct McpAccess {
    pub enabled: bool,
    /// Resource types as `plural` (core) or `plural.group`, e.g. "pods", "deployments.apps".
    pub resources: Vec<String>,
    /// Empty = every namespace.
    pub namespaces: Vec<String>,
    /// Full manifests (get_resource). Off = table rows only.
    pub objects: bool,
    pub logs: bool,
    pub events: bool,
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
#[serde(rename_all = "camelCase", default)]
pub struct Settings {
    // Older versions wrote snake_case.
    #[serde(alias = "kubeconfig_folders")]
    pub kubeconfig_folders: Vec<PathBuf>,
    pub clusters: BTreeMap<String, ClusterSettings>,
    /// "system" | "dark" | "light"
    pub theme: String,
    pub helm_path: Option<String>,
    pub kubectl_path: Option<String>,
    /// Download kubectl matching each cluster's version for cluster terminals.
    pub kubectl_auto: bool,
    pub terminal_shell: Option<String>,
    pub terminal_font_size: u16,
    /// Updater feed (a latest.json URL) and the matching minisign public key.
    pub update_endpoint: Option<String>,
    pub update_pubkey: Option<String>,
    /// Extension ids (folder names) turned off in Settings.
    pub disabled_extensions: Vec<String>,
    /// Local MCP server (127.0.0.1 only, bearer token).
    pub mcp_enabled: bool,
    pub mcp_port: u16,
    /// Generated by the backend on first start; never taken from the UI.
    pub mcp_token: Option<String>,
}

impl Default for Settings {
    fn default() -> Self {
        Settings {
            kubeconfig_folders: vec![],
            clusters: BTreeMap::new(),
            theme: "system".into(),
            helm_path: None,
            kubectl_path: None,
            kubectl_auto: true,
            terminal_shell: None,
            terminal_font_size: 13,
            update_endpoint: None,
            update_pubkey: None,
            disabled_extensions: vec![],
            mcp_enabled: false,
            mcp_port: 7420,
            mcp_token: None,
        }
    }
}

/// ~/.config/kube-portal: settings.db, pasted kubeconfigs, extensions.
pub fn config_dir() -> Result<PathBuf> {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
        .or_else(|| dirs::home_dir().map(|h| h.join(".config")))
        .ok_or("no home directory")?;
    Ok(base.join("kube-portal"))
}

/// The folder and database hold the MCP token and pasted credentials, so only the owner may read them.
#[cfg(unix)]
fn restrict(path: &Path, mode: u32) {
    use std::os::unix::fs::PermissionsExt;
    if let Ok(meta) = std::fs::metadata(path) {
        if meta.permissions().mode() & 0o777 != mode {
            let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode));
        }
    }
}

fn open_db() -> Result<rusqlite::Connection> {
    let dir = config_dir()?;
    std::fs::create_dir_all(&dir).map_err(err)?;
    let path = dir.join("settings.db");
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        let _ = std::fs::OpenOptions::new().write(true).create(true).truncate(false).mode(0o600).open(&path);
        restrict(&dir, 0o700);
        restrict(&path, 0o600);
    }
    let db = rusqlite::Connection::open(&path).map_err(err)?;
    db.execute("CREATE TABLE IF NOT EXISTS kv (key TEXT PRIMARY KEY, value TEXT NOT NULL)", [])
        .map_err(err)?;
    Ok(db)
}

/// Folder holding kubeconfigs added through "Add cluster"; always scanned.
pub fn managed_dir() -> Result<PathBuf> {
    Ok(config_dir()?.join("kubeconfigs"))
}

/// One-time move from the old per-OS app config dir (settings.json, kubeconfigs/, extensions/).
pub fn migrate_legacy(app: &AppHandle) {
    let (Ok(old), Ok(new)) = (app.path().app_config_dir(), config_dir()) else { return };
    let _ = std::fs::create_dir_all(&new);
    for name in ["kubeconfigs", "extensions"] {
        if old.join(name).is_dir() && !new.join(name).exists() {
            let _ = std::fs::rename(old.join(name), new.join(name));
        }
    }
    let json = old.join("settings.json");
    let Ok(text) = std::fs::read_to_string(&json) else { return };
    let Ok(db) = open_db() else { return };
    let has_row = db.query_row("SELECT 1 FROM kv WHERE key = 'settings'", [], |_| Ok(())).is_ok();
    if !has_row {
        if let Ok(s) = serde_json::from_str::<Settings>(&text) {
            if save(&s).is_err() {
                return;
            }
        }
    }
    let _ = std::fs::rename(&json, old.join("settings.json.migrated"));
}

pub fn load() -> Settings {
    open_db()
        .ok()
        .and_then(|db| db.query_row("SELECT value FROM kv WHERE key = 'settings'", [], |r| r.get::<_, String>(0)).ok())
        .and_then(|s| serde_json::from_str::<Settings>(&s).ok())
        .unwrap_or_default()
}

pub fn save(s: &Settings) -> Result<()> {
    let json = serde_json::to_string(s).map_err(err)?;
    open_db()?
        .execute("INSERT INTO kv (key, value) VALUES ('settings', ?1) ON CONFLICT(key) DO UPDATE SET value = excluded.value", [json])
        .map_err(err)?;
    Ok(())
}

pub fn write_private(path: &Path, data: &[u8]) -> std::io::Result<()> {
    use std::io::Write;
    let mut opts = std::fs::OpenOptions::new();
    opts.write(true).create(true).truncate(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        opts.mode(0o600);
    }
    opts.open(path)?.write_all(data)
}

